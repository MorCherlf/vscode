import { readFile, writeFile } from 'node:fs/promises';
import { parse } from 'jsonc-parser';

// Snapshot only the colors used by this client from this checkout's VS Code themes.
const aliases = {
	foreground: 'foreground', descriptionForeground: 'descriptionForeground',
	'editor-background': 'editor.background', 'sideBar-background': 'sideBar.background',
	'button-background': 'button.background', 'button-foreground': 'button.foreground',
	'button-hoverBackground': 'button.hoverBackground', 'widget-border': 'editorGroup.border',
	'input-background': 'input.background', 'input-foreground': 'input.foreground',
	'input-placeholderForeground': 'input.placeholderForeground', 'input-border': 'input.border',
	'list-hoverBackground': 'list.hoverBackground', 'list-activeSelectionBackground': 'list.activeSelectionBackground',
	'list-activeSelectionForeground': 'list.activeSelectionForeground', focusBorder: 'focusBorder',
	errorForeground: 'errorForeground', 'textCodeBlock-background': 'textCodeBlock.background',
};
const blocks = [];
async function readColors(file) {
	const errors = [];
	const theme = parse(await readFile(file, 'utf8'), errors, { allowTrailingComma: true });
	if (errors.length) { throw new Error('Invalid upstream theme: ' + file); }
	return { ...(theme.include ? await readColors(new URL(theme.include, file)) : {}), ...theme.colors };
}
for (const kind of ['light', 'dark']) {
	const colors = await readColors(new URL('../../../extensions/theme-defaults/themes/' + kind + '_modern.json', import.meta.url));
	// listColors.ts supplies registry defaults when a theme does not override them.
	colors['list.hoverBackground'] ??= kind === 'dark' ? '#2A2D2E' : '#F0F0F0';
	colors['list.activeSelectionBackground'] ??= kind === 'dark' ? '#04395E' : '#0060C0';
	colors['list.activeSelectionForeground'] ??= '#FFFFFF';
	const lines = Object.entries(aliases).map(([token, color]) => {
		const value = colors[color] ?? (token === 'textCodeBlock-background' ? colors['input.background'] : undefined);
		if (!value) { throw new Error('Missing theme token: ' + color); }
		return '\t--vscode-' + token + ': ' + value + ';';
	});
	lines.push('\tcolor-scheme: ' + kind + ';');
	const declarations = lines.join('\n');
	blocks.push((kind === 'light' ? ':root, ' : '') + ':root[data-theme="' + kind + '"] {\n' + declarations + '\n}');
	if (kind === 'dark') { blocks.push('@media (prefers-color-scheme: dark) {\n:root:not([data-theme="light"]):not([data-theme="dark"]) {\n' + declarations + '\n}\n}'); }
}
await writeFile(new URL('../src/theme-colors.css', import.meta.url), '/* Copyright (c) Microsoft Corporation. All rights reserved. */\n/* Licensed under the MIT License. See LICENSE.txt in the project root for license information. */\n/* Generated by scripts/sync-vscode-theme.mjs from VS Code Light/Dark Modern. */\n' + blocks.join('\n\n') + '\n');
